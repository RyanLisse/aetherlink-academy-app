#!/usr/bin/env node
import { createServer } from 'node:http';
import { readFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const outDir = path.join(root, 'artifacts/aet-63');
mkdirSync(outDir, { recursive: true });

if (!existsSync(path.join(dist, 'index.html'))) {
  console.error('dist/index.html missing — run CI=true pnpm run build:legacy first');
  process.exit(1);
}

const mime = {
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.css': 'text/css',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.map': 'application/json',
};

const server = createServer((req, res) => {
  const url = new URL(req.url || '/', 'http://127.0.0.1');
  let filePath = path.join(dist, decodeURIComponent(url.pathname));
  if (url.pathname === '/' || url.pathname.startsWith('/arcade') || !existsSync(filePath) || !path.resolve(filePath).startsWith(dist)) {
    filePath = path.join(dist, 'index.html');
  }
  try {
    const body = readFileSync(filePath);
    res.writeHead(200, { 'Content-Type': mime[path.extname(filePath)] || 'application/octet-stream' });
    res.end(body);
  } catch {
    res.writeHead(404);
    res.end('missing');
  }
});

await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
const { port } = server.address();
const base = `http://127.0.0.1:${port}`;

try {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  await page.goto(base + '/arcade/sdk-bridge', { waitUntil: 'domcontentloaded', timeout: 30000 });
  await page.waitForSelector('.arcade-ready, .arcade-pending', { timeout: 15000 });
  await page.waitForTimeout(400);
  await page.screenshot({ path: path.join(outDir, 'arcade-sdk-ready.png'), fullPage: true });
  const pending = await page.locator('.arcade-pending').count();
  const ready = await page.locator('.arcade-ready').count();
  const text = await page.locator('body').innerText();
  writeFileSync(path.join(outDir, 'proof.json'), JSON.stringify({ pending, ready, hasAvailableCopy: /SDK starters ready|available/i.test(text) }, null, 2));
  if (pending > 0) throw new Error('PENDING panel still visible on /arcade/sdk-bridge');
  if (ready < 1) throw new Error('ready panel missing on /arcade/sdk-bridge');
  await page.goto(base + '/arcade', { waitUntil: 'domcontentloaded', timeout: 30000 });
  await page.waitForTimeout(300);
  await page.screenshot({ path: path.join(outDir, 'arcade-hub-ready.png'), fullPage: true });
  writeFileSync(path.join(outDir, 'README.md'), '# AET-63 screenshots\n\nGenerated by scripts/aet-63-screenshots.mjs\n\n- arcade-sdk-ready.png — starters available (not PENDING)\n- arcade-hub-ready.png — hub available pill\n');
  console.log('wrote screenshots to', outDir, { pending, ready });
  await browser.close();
} catch (error) {
  console.error('screenshot failed', error);
  process.exitCode = 1;
} finally {
  server.close();
}
