#!/usr/bin/env node
import { createServer } from 'node:http';
import { readFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const outDir = path.join(root, 'artifacts/lis-60');
mkdirSync(outDir, { recursive: true });

if (!existsSync(path.join(dist, 'index.html'))) {
  console.error('dist/index.html missing — run CI=true pnpm run build:legacy first');
  process.exit(1);
}

const mime = {
  '.html': 'text/html',
  '.js': 'text/javascript',
  '.css': 'text/css',
  '.json': 'application/json',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.map': 'application/json',
};

const server = createServer((req, res) => {
  const url = new URL(req.url || '/', 'http://127.0.0.1');
  let filePath = path.join(dist, decodeURIComponent(url.pathname));
  if (url.pathname === '/' || url.pathname.startsWith('/arcade') || !existsSync(filePath) || !path.resolve(filePath).startsWith(dist)) {
    filePath = path.join(dist, 'index.html');
  }
  try {
    const body = readFileSync(filePath);
    res.writeHead(200, { 'Content-Type': mime[path.extname(filePath)] || 'application/octet-stream' });
    res.end(body);
  } catch {
    res.writeHead(404).end('missing');
  }
});

await new Promise((resolve) => server.listen(4371, '127.0.0.1', resolve));
const base = 'http://127.0.0.1:4371';
console.log('preview', base);

try {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.goto(base + '/arcade', { waitUntil: 'networkidle' });
  await page.waitForSelector('[data-arcade="true"]');
  await page.screenshot({ path: path.join(outDir, 'arcade-hub.png'), fullPage: true });
  await page.goto(base + '/arcade/weather', { waitUntil: 'networkidle' });
  await page.waitForSelector('.arcade-lesson');
  await page.screenshot({ path: path.join(outDir, 'arcade-weather.png'), fullPage: true });
  await page.getByRole('button', { name: 'Tech' }).click();
  await page.screenshot({ path: path.join(outDir, 'arcade-weather-tech.png'), fullPage: true });
  await page.goto(base + '/arcade/sdk-bridge', { waitUntil: 'networkidle' });
  await page.waitForSelector('.arcade-pending');
  await page.screenshot({ path: path.join(outDir, 'arcade-sdk-pending.png'), fullPage: true });
  await browser.close();
  writeFileSync(path.join(outDir, 'README.md'), '# LIS-60 screenshots\n\nGenerated by scripts/lis-60-screenshots.mjs\n');
  console.log('wrote screenshots to', outDir);
} catch (error) {
  console.error('screenshot failed', error);
  process.exitCode = 1;
} finally {
  server.close();
}
