#!/usr/bin/env node
/**
 * Re-import jyse/aetherlink-classroom-slides into apps/web/src/deck/slides.ts.
 * Does not invent curriculum — copies slides.js body only, swapping the SoT
 * `window.SLIDES` binding for the platform `export const sourceSlides`.
 *
 * Usage:
 *   node scripts/sync-classroom-slides-from-sot.mjs [path-to-sot-checkout]
 *
 * Env:
 *   SOURCE_DECK_DIR — SoT checkout (default: /tmp/aetherlink-classroom-slides)
 *   SOT_TIP         — optional tip SHA to stamp in the header (default: git rev-parse HEAD in SoT)
 */
import {readFileSync, writeFileSync, existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sotDir = resolve(
  process.argv[2] || process.env.SOURCE_DECK_DIR || '/tmp/aetherlink-classroom-slides',
);
const sotSlides = join(sotDir, 'slides.js');
const outPath = join(appRoot, 'apps/web/src/deck/slides.ts');

if (!existsSync(sotSlides)) {
  console.error(`SoT slides.js not found at ${sotSlides}`);
  process.exit(1);
}

function git(cwd, args) {
  return execFileSync('git', args, {cwd, encoding: 'utf8'}).trim();
}

const tip =
  process.env.SOT_TIP ||
  git(sotDir, ['rev-parse', 'HEAD']);
const short = tip.slice(0, 8);
const branch = (() => {
  try {
    return git(sotDir, ['rev-parse', '--abbrev-ref', 'HEAD']);
  } catch {
    return 'cons/cursus-aanpassingen';
  }
})();

const raw = readFileSync(sotSlides, 'utf8');
const marker = 'window.SLIDES = [';
const idx = raw.indexOf(marker);
if (idx === -1) {
  console.error('SoT slides.js has no window.SLIDES = [ binding');
  process.exit(1);
}

const preamble = raw.slice(0, idx); // field-reference comment block
const arrayAndRest = raw.slice(idx + 'window.SLIDES'.length); // " = [\n..." through end

const header =
  `/** Synced from jyse/aetherlink-classroom-slides @ ${branch} tip ${short}.\n` +
  ` *  Do not hand-edit curriculum prose — re-sync from SoT. Day 1 ends before the "TEACHING DAY 2" divider (see normalize.ts).\n` +
  ` *  Full tip: ${tip}\n` +
  ` *  Regenerated by: node scripts/sync-classroom-slides-from-sot.mjs\n` +
  ` */\n`;

const next = header + preamble + 'export const sourceSlides' + arrayAndRest;
writeFileSync(outPath, next);
console.log(
  JSON.stringify(
    {
      out: outPath,
      sotDir,
      tip,
      short,
      branch,
      bytes: next.length,
    },
    null,
    2,
  ),
);
